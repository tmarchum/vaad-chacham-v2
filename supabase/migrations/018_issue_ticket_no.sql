-- 018_issue_ticket_no.sql — human-readable ticket numbers ("קריאה #1042").
-- Residents and vendors can quote a short number instead of a UUID.
-- BY DEFAULT (not ALWAYS) so whole-row client updates that echo the column
-- back are accepted. Existing rows are numbered in insertion order.
alter table public.issues
  add column if not exists ticket_no bigint generated by default as identity (start with 1001);
create unique index if not exists issues_ticket_no_key on public.issues (ticket_no);
